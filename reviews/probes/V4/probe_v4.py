"""V4 paper probe. Read-only on the repo except this file's own log.

Does not call write_numbers.main(), which would overwrite numbers.tex.
"""
from __future__ import annotations

import json
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "src"))

THESIS = ROOT / "thesis"
SECTIONS = list((THESIS / "sections").glob("*.tex")) + [THESIS / "main.tex"]
LOG = Path(__file__).with_name("probe_v4.log")


def section(title: str) -> None:
    print(f"\n===== {title} =====")


def load_json(rel: str) -> dict:
    return json.loads((ROOT / rel).read_text())


def regen_numbers() -> str:
    import write_numbers as wn

    rows = wn.table()
    lines = [
        "% numbers.tex: GENERATED by scripts/write_numbers.py from config/ and results/.",
        "% Do not edit by hand. Rerun the script after any run.",
        "",
    ]
    lines += [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in rows]
    return "\n".join(lines) + "\n", rows


def parse_macros(text: str) -> dict[str, str]:
    out = {}
    for m in re.finditer(r"\\newcommand\{\\([A-Za-z]+)\}\{(.+)\}", text):
        out[m.group(1)] = m.group(2)
    return out


def strip_comments(text: str) -> str:
    return "\n".join(line.split("%", 1)[0] for line in text.splitlines())


def main() -> int:
    fails = 0
    section("1 numbers byte identity")
    fresh, rows = regen_numbers()
    thesis_text = (THESIS / "numbers.tex").read_text()
    writeup_text = (ROOT / "writeup" / "numbers.tex").read_text()
    print(f"fresh_bytes={len(fresh.encode())} thesis_bytes={len(thesis_text.encode())} writeup_bytes={len(writeup_text.encode())}")
    print(f"thesis_equals_fresh={thesis_text == fresh}")
    print(f"writeup_equals_fresh={writeup_text == fresh}")
    print(f"n_macros={len(rows)}")
    if thesis_text != fresh:
        fails += 1
        # first differing line
        a, b = thesis_text.splitlines(), fresh.splitlines()
        print(f"line_count thesis={len(a)} fresh={len(b)}")
        for i, (x, y) in enumerate(zip(a, b), 1):
            if x != y:
                print(f"first_diff_line={i}")
                print(f"  thesis: {x[:200]}")
                print(f"  fresh:  {y[:200]}")
                break
        else:
            print("prefix_equal_lengths_differ")

    macros = parse_macros(thesis_text)
    section("1b macro resolution and typed literals")
    defined_local = set(macros)
    # commands defined in the paper itself
    for path in SECTIONS:
        body = path.read_text()
        for m in re.finditer(r"\\(?:newcommand|renewcommand|providecommand)\{\\([A-Za-z]+)", body):
            defined_local.add(m.group(1))
    used_camel = {}
    literals = []
    missing_names = []
    for path in SECTIONS:
        raw = path.read_text()
        for i, line in enumerate(raw.splitlines(), 1):
            code = line.split("%", 1)[0]
            for m in re.finditer(r"\\MISSING\{([A-Za-z0-9]+)\}", code):
                missing_names.append((path.name, i, m.group(1)))
            for m in re.finditer(r"\\([A-Z][A-Za-z0-9]+)", code):
                name = m.group(1)
                used_camel.setdefault(name, []).append(f"{path.name}:{i}")
            # decimals and integers that are not inside a macro name
            for m in re.finditer(r"(?<![A-Za-z\\])(\d+\.\d+|\d{2,})", code):
                token = m.group(1)
                # skip if this number is the argument of a length like 0.92\linewidth already captured
                literals.append((path.name, i, token, code.strip()[:160]))
    unresolved = sorted(n for n in used_camel if n not in defined_local)
    print(f"camel_used={len(used_camel)} unresolved={unresolved}")
    for n in unresolved:
        print(f"  UNRESOLVED {n} at {used_camel[n][:4]}")
    print(f"MISSING_count={len(missing_names)}")
    for row in missing_names:
        print(f"  MISSING {row[0]}:{row[1]} {row[2]}")
    # collapse literals
    print(f"literal_hits={len(literals)}")
    # print decimals always; integers only if not a year-like or tiny structural
    seen = set()
    for name, i, token, ctx in literals:
        key = (name, i, token)
        if key in seen:
            continue
        seen.add(key)
        if "." in token or (token.isdigit() and int(token) >= 50 and not (1900 <= int(token) <= 2030)):
            print(f"  LIT {name}:{i} {token} | {ctx}")

    section("2-4 claims against JSON")
    T = load_json("results/interference/tradeoff.json")
    points = ["min_I", "median_I", "c_star"]
    analysts = ["A0", "A1", "A2"]
    print(f"Theta_hm={T['Theta_hm']} width={T['theta_hm_width']} R={T['repetitions']}")
    exp = {k: True for k in "abcde"}
    exp_notes = []
    se_over = {}
    for p in points:
        block = T["points"][p]
        print(f"\n-- {p} theta2_true={block['theta2_true']} planted={block['theta2_planted']}")
        one = block["one_panel"]
        for a in analysts:
            o = one[a]
            print(
                f"  one {a} est={o['estimate']:.6g} iv={o['interval']} "
                f"covers_truth={o['covers_truth']} covers_planted={o['covers_planted_truth']} "
                f"verdict={o['vs_Theta_hm']}"
            )
        rep = block["repeated"]
        biases = {a: rep[a]["bias"] for a in analysts}
        sds = {a: rep[a]["sd"] for a in analysts}
        widths = {a: rep[a]["mean_width"] for a in analysts}
        covs = {a: rep[a]["coverage"] for a in analysts}
        rmses = {a: rep[a]["rmse"] for a in analysts}
        absb = {a: abs(biases[a]) for a in analysts}
        print(f"  bias={ {a: round(biases[a], 6) for a in analysts} }")
        print(f"  sd={ {a: round(sds[a], 6) for a in analysts} }")
        print(f"  width={ {a: round(widths[a], 6) for a in analysts} }")
        print(f"  coverage={covs}")
        print(f"  rmse={ {a: round(rmses[a], 6) for a in analysts} }")
        print(f"  se_over_sd={ {a: round(rep[a]['se_over_sd'], 4) for a in analysts} }")
        print(f"  width_ratio={ {a: round(rep[a]['width_over_theta_hm'], 4) for a in analysts} }")
        print(f"  undefined={ {a: rep[a]['undefined_count'] for a in analysts} }")
        for a in ("A1", "A2"):
            se_over[(p, a)] = rep[a]["se_over_sd"]
        if not (absb["A0"] > absb["A1"] > absb["A2"]):
            exp["a"] = False
            exp_notes.append(f"(a) fail at {p}: {absb}")
        if not (sds["A0"] < sds["A1"] < sds["A2"] and widths["A0"] < widths["A1"] < widths["A2"]):
            exp["b"] = False
            exp_notes.append(f"(b) fail at {p}: sd={sds} width={widths}")
        # (c) A0 far below 0.95; closest is a tie if A1==A2 and both closer than A0
        dist = {a: abs(covs[a] - 0.95) for a in analysts}
        closest = min(dist.values())
        winners = [a for a in analysts if dist[a] == closest]
        if not (covs["A0"] < 0.5 and set(winners) == {"A1", "A2"}):
            exp["c"] = False
            exp_notes.append(f"(c) not a tie-at-1 at {p}: cov={covs} winners={winners}")
        if not (biases["A1"] < 0 and biases["A2"] < 0):
            exp["d"] = False
            exp_notes.append(f"(d) fail at {p}: {biases}")
        if not all(rep[a]["width_over_theta_hm"] < 1 for a in analysts):
            exp["e"] = False
            exp_notes.append(f"(e) fail at {p}")
        if rmses["A1"] >= min(rmses["A0"], rmses["A2"]):
            exp_notes.append(f"RMSE claim fail at {p}: {rmses}")
    print(f"expectations_met_as_paper_states={exp}")
    for note in exp_notes:
        print(f"  NOTE {note}")
        fails += 1
    vals = list(se_over.values())
    print(f"A1A2_se_over_sd_min={min(vals):.6g} max={max(vals):.6g}")
    print("se_over_sd_detail=" + ", ".join(f"{p}:{a}={se_over[(p, a)]:.6g}" for p in points for a in ("A1", "A2")))

    # headline clauses
    section("headline clauses")
    # clause: A0 misses at c* one panel
    cstar = T["points"]["c_star"]["one_panel"]
    print(f"cstar_A0_misses={cstar['A0']['covers_truth'] is False}")
    print(f"cstar_A0_verdict={cstar['A0']['vs_Theta_hm']}")
    for p in ("min_I", "median_I"):
        op = T["points"][p]["one_panel"]
        print(
            f"{p} A0 covers_truth={op['A0']['covers_truth']} covers_planted={op['A0']['covers_planted_truth']} "
            f"verdict={op['A0']['vs_Theta_hm']}"
        )
        for a in ("A1", "A2"):
            print(
                f"{p} {a} covers_truth={op[a]['covers_truth']} covers_planted={op[a]['covers_planted_truth']} "
                f"verdict={op[a]['vs_Theta_hm']}"
            )
    # repeated: |bias| falls and SD rises at every diagnostic point — already in exp
    print(f"abs_bias_falls_all_points={exp['a']} sd_rises={exp['b']}")

    section("planted foil flags and image")
    P = load_json("results/planted/poc_results.json")
    # print top keys and hunt foil / image fields without dumping the file
    print("planted_top_keys=" + ",".join(sorted(P.keys())[:40]))

    def walk(obj, prefix, hits, depth=0):
        if depth > 4:
            return
        if isinstance(obj, dict):
            for k, v in obj.items():
                lk = str(k).lower()
                if any(s in lk for s in ("foil", "theta_hm", "theta_exp", "cover", "verdict", "image", "spread", "recheck", "premium", "spill")):
                    if not isinstance(v, (dict, list)) or (isinstance(v, list) and v and not isinstance(v[0], (dict, list))):
                        hits.append(f"{prefix}.{k}={v}")
                walk(v, f"{prefix}.{k}", hits, depth + 1)
        elif isinstance(obj, list) and obj and isinstance(obj[0], dict) and len(obj) <= 8:
            for i, item in enumerate(obj):
                walk(item, f"{prefix}[{i}]", hits, depth + 1)

    hits = []
    walk(P, "planted", hits)
    for h in hits[:80]:
        print(h)
    print(f"planted_hit_count={len(hits)}")

    section("sixth-decimal and allowance")
    # recheck file
    recheck_paths = list((ROOT / "results").rglob("*recheck*.json")) + list((ROOT / "results").rglob("*endpoint*.json"))
    print("recheck_files=" + ",".join(str(p.relative_to(ROOT)) for p in recheck_paths))
    for p in recheck_paths:
        data = json.loads(p.read_text())
        print(f"file {p.name} keys={list(data)[:20]}")

    # delta allowance vs theta1 from config via the already-imported module
    import poc_abm.config as C

    tau = C.HM_TAU if hasattr(C, "HM_TAU") else None
    # print relevant config names
    names = [n for n in dir(C) if n.isupper()]
    print("config_names=" + ",".join(names))
    return 0 if fails == 0 else 1


if __name__ == "__main__":
    rc = main()
    print(f"\nPROBE_EXIT_INTENT={rc}")
    sys.exit(rc)
